-- Employee Management schema (Oracle 12c+)
-- Run once in SQL Developer while connected as the application user.

CREATE TABLE departments (
  id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name  VARCHAR2(100) NOT NULL CONSTRAINT uk_dept_name UNIQUE
);

CREATE TABLE employees (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name    VARCHAR2(50)  NOT NULL,
  last_name     VARCHAR2(50)  NOT NULL,
  email         VARCHAR2(120) NOT NULL CONSTRAINT uk_emp_email UNIQUE,
  phone         VARCHAR2(20),
  job_title     VARCHAR2(100),
  salary        NUMBER(12,2)  CONSTRAINT ck_emp_salary CHECK (salary > 0),
  hire_date     DATE,
  department_id NUMBER NOT NULL CONSTRAINT fk_emp_dept REFERENCES departments(id)
);

CREATE INDEX ix_emp_department ON employees(department_id);
