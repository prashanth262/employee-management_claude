-- Employee Management schema (H2). Runs on every startup; IF NOT EXISTS keeps existing data.

CREATE TABLE IF NOT EXISTS departments (
  id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name  VARCHAR(100) NOT NULL CONSTRAINT uk_dept_name UNIQUE
);

CREATE TABLE IF NOT EXISTS employees (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name    VARCHAR(50)  NOT NULL,
  last_name     VARCHAR(50)  NOT NULL,
  email         VARCHAR(120) NOT NULL CONSTRAINT uk_emp_email UNIQUE,
  phone         VARCHAR(20),
  job_title     VARCHAR(100),
  salary        DECIMAL(12,2) CONSTRAINT ck_emp_salary CHECK (salary > 0),
  hire_date     DATE,
  department_id BIGINT NOT NULL CONSTRAINT fk_emp_dept REFERENCES departments(id)
);

CREATE INDEX IF NOT EXISTS ix_emp_department ON employees(department_id);

-- Records that sample data has been loaded, so data.sql only seeds a brand-new database
CREATE TABLE IF NOT EXISTS ems_seed (seeded_at TIMESTAMP NOT NULL);
